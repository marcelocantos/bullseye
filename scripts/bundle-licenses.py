"""Bundle release dependency notices; --check refuses stale or missing text.

Requires cargo-bundle-licenses 5.0.0 (`cargo install --locked
cargo-bundle-licenses --version 5.0.0`). Run with uv run --script.
"""

import argparse
import json
import os
from pathlib import Path
import subprocess


ROOT = Path(__file__).resolve().parent.parent
PLATFORMS = (
    "aarch64-apple-darwin",
    "x86_64-unknown-linux-gnu",
    "aarch64-unknown-linux-gnu",
)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--output", type=Path, default=ROOT / "THIRDPARTY.txt")
    args = parser.parse_args()
    packages = {}
    for platform in PLATFORMS:
        metadata = json.loads(subprocess.check_output(
            ["cargo", "metadata", "--locked", "--format-version", "1",
             "--filter-platform", platform], cwd=ROOT,
        ))
        nodes = {node["id"]: node for node in metadata["resolve"]["nodes"]}
        pending = [metadata["resolve"]["root"]]
        seen = set()
        while pending:
            key = pending.pop()
            if key in seen:
                continue
            seen.add(key)
            pending.extend(dep["pkg"] for dep in nodes[key]["deps"]
                           if any(kind["kind"] != "dev" for kind in dep["dep_kinds"]))
        for package in metadata["packages"]:
            if package["id"] in seen and package["id"] != metadata["resolve"]["root"]:
                packages[(package["name"], package["version"])] = package

    bundle = json.loads(subprocess.check_output(
        ["cargo", "bundle-licenses", "--format", "json"], cwd=ROOT,
        env={**os.environ, "RUST_LOG": "error"},
    ))
    licenses = {(entry["package_name"], entry["package_version"]): entry
                for entry in bundle["third_party_libraries"]}
    output = ["Third-party dependency licenses\n===============================\n\n",
              "Generated by scripts/bundle-licenses.py from the locked release dependency\n",
              "graphs for macOS arm64 and Linux x86_64/arm64, including build dependencies.\n",
              "Development-only dependencies and unsupported platforms are excluded.\n\n"]
    shared_texts = {}
    for key, package in sorted(packages.items()):
        # The upstream bundler omits build-only crates; their shipped license
        # files are collected below just like the runtime crates' supplements.
        entry = licenses.get(key, {"license": package["license"],
                                   "repository": package["repository"], "licenses": []})
        output.append(f"\n{'=' * 72}\n{key[0]} {key[1]}\n")
        output.append(f"Declared license: {entry['license']}\n")
        output.append(f"Upstream: {entry['repository']}\n\n")
        texts = set()
        for license in sorted(entry["licenses"], key=lambda item: (item["license"], item["text"])):
            text = license["text"].strip()
            if not text or text == "NOT FOUND":
                raise SystemExit(f"Missing {license['license']} text for {key}")
            if text not in texts:
                number = shared_texts.setdefault(text, len(shared_texts) + 1)
                output.append(f"{license['license']}: license text #{number}\n")
                texts.add(text)

        # Crate-level license files can refer to additional notices in subtrees
        # (notably ring's BoringSSL and once_cell code). Include those verbatim too.
        directory = Path(package["manifest_path"]).parent
        for path in sorted(directory.rglob("*")):
            if path.is_symlink() or not path.is_file():
                continue
            if not path.name.upper().startswith(("LICENSE", "LICENCE", "COPYING", "NOTICE", "COPYRIGHT", "UNLICENSE")):
                continue
            text = path.read_text(encoding="utf-8").strip()
            if text and text not in texts:
                number = shared_texts.setdefault(text, len(shared_texts) + 1)
                output.append(f"{path.relative_to(directory)}: license text #{number}\n")
                texts.add(text)
        if not texts:
            raise SystemExit(f"No dependency license text for {key}")
    for text, number in shared_texts.items():
        output.append(f"\n{'=' * 72}\nLicense text #{number}\n\n{text}\n")
    text = "".join(output)
    if args.check:
        if not args.output.exists() or args.output.read_bytes() != text.encode("utf-8"):
            raise SystemExit("Dependency license bundle is missing/stale; run uv run --script scripts/bundle-licenses.py")
    else:
        args.output.write_bytes(text.encode("utf-8"))
    print(f"Dependency license bundle {'verified' if args.check else 'written'}: {len(packages)} packages")


if __name__ == "__main__":
    main()
